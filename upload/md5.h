#ifndef MD5_H
#define MD5_H

/******************************************************************************
 * md5.h — MD5 消息摘要算法（RFC 1321）
 *
 * 为什么自己实现而不用 OpenSSL？
 *   项目目前只需要 MD5 这一个哈希算法，OpenSSL 的 libcrypto 体积大、依赖重。
 *   RFC 1321 的参考实现约 300 行 C 代码，无外部依赖，完全契合本项目的轻量风格。
 *
 * 用途：
 *   文件上传完成后，服务器对接收到的文件计算 MD5，与客户端提供的预期值比对，
 *   从而验证文件在传输过程中是否完整无损。
 *
 * 接口分为两层：
 *   1. 底层：MD5_Init / MD5_Update / MD5_Final —— 增量式哈希，适合流式处理
 *   2. 上层：md5_file() —— 一步完成"打开文件 → 分块读取 → 计算 MD5 → 返回 hex 字符串"
 ******************************************************************************/

#include <stdint.h>   // uint32_t, size_t
#include <string>      // std::string（返回值用）

// ---------------------------------------------------------------------------
// MD5 计算上下文（状态保持结构体）
// ---------------------------------------------------------------------------
// 因为 MD5 是增量式算法，数据可能分多次喂入（比如读文件时 8KB 一次）。
// 这个结构体在两次 MD5_Update 调用之间保持中间状态。
typedef struct {
    uint32_t state[4];           // 四个 32 位状态寄存器 A、B、C、D（MD5 的核心）
    uint32_t count[2];           // 已处理的比特总数（低位字、高位字），用于最后填充
    unsigned char buffer[64];   // 输入缓冲区：攒够 512 bit（64 字节）就压缩一次
} MD5_CTX;

// ---------------------------------------------------------------------------
// MD5 底层接口（三步走：初始化 → 多次更新 → 终结）
// ---------------------------------------------------------------------------

// 初始化上下文：设置 A/B/C/D 的初始魔数，计数清零，缓冲区清零
void MD5_Init(MD5_CTX *ctx);

// 喂入数据：可多次调用，每次喂入任意长度的数据块。
// ctx —— MD5 上下文指针（保持中间状态）
// input —— 指向待哈希数据的指针
// len —— 数据长度（字节）
void MD5_Update(MD5_CTX *ctx, const unsigned char *input, size_t len);

// 终结计算：对剩余不足 512bit 的数据做填充（padding），
//           最后做一轮 MD5 压缩，输出 16 字节的原始摘要。
// digest —— 输出缓冲区（必须是 unsigned char[16]）
void MD5_Final(unsigned char digest[16], MD5_CTX *ctx);

// ---------------------------------------------------------------------------
// 便捷接口：一步完成"文件 → MD5 hex 字符串"
// ---------------------------------------------------------------------------
// 内部流程：fopen → 循环 fread（8KB）→ MD5_Update → MD5_Final → 转 hex
//
// 返回值：
//   成功 → 32 个字符的小写十六进制字符串（例如 "d41d8cd98f00b204e9800998ecf8427e"）
//   失败（文件不存在 / 打不开）→ 空字符串 ""
std::string md5_file(const char *filepath);

#endif
